"""Generated blocks: REPOS.md, map/DEPLOY.md, map/BRIDGES.md, <infra>/DEPLOY.md. The model writes prose outside the blocks."""
from collections import defaultdict

from .render import mermaid_id, put_block, table

REPOS_HEADER = "# Repositories\n\nOne row per tracked project. The table is generated by `ando status`; edit text outside it."
DEPLOY_HEADER = "# Deploy map\n\nWhat runs where, joined from the infra inventories and the images each project builds."
BRIDGES_HEADER = "# Bridges\n\nHow the systems talk to each other. Edges come from code ports and from deploy config."


def repos(target, rows):
    body = table(["slug", "kind", "repo", "branch", "path", "baseline", "behind", "status", "deployed as", "open questions"],
                 [[r["slug"], r["kind"], r["repo"], r["branch"], r["path"], r["baseline"], r["behind"], r["status"],
                   r["deployed"], r["questions"]] for r in rows])
    put_block(target.root / "REPOS.md", "repos", body, REPOS_HEADER)


def deployed_as(deploy, slug):
    names = set()
    for e in (deploy or {}).get("images", {}).values():
        if any(b["project"] == slug for b in e["builders"]):
            names.update(w["name"] for w in e["workloads"])
    return names


def deploy_map(target, deploy):
    rows, orphans, untracked, disabled = [], [], [], []
    for key, e in deploy["images"].items():
        src = ", ".join(f"{b['project']}:`{b['from']}`" + (" (excluded)" if b["excluded"] else "") for b in e["builders"]) or "?"
        for w in e["workloads"]:
            if not w.get("live", True):
                disabled.append([w["namespace"], w["name"], f"`{key}:{w['tag'] or ''}`", src, f"`{w['file']}`"])
                continue
            run = f"cron `{w['schedule']}`" if w["schedule"] else ""
            if w.get("suspended"):
                run += " suspended"
            rows.append([w["namespace"], w["name"], w["kind"], f"`{key}:{w['tag'] or ''}`", src, run,
                         ", ".join(w["hosts"]), w.get("variant") or "", ", ".join(w.get("apps") or [])])
        if e["builders"] and not any(w.get("live", True) for w in e["workloads"]):
            orphans.extend(f"{b['project']}:`{b['from']}` builds `{key}`" + (" (excluded path)" if b["excluded"] else "") for b in e["builders"])
        if any(w.get("live", True) for w in e["workloads"]) and not e["builders"] and e["ours"]:
            untracked.append(f"`{key}` ({', '.join(sorted({w['name'] for w in e['workloads']}))})")
    rows.sort(key=lambda r: (r[0] or "", r[1] or ""))
    ours = [r for r in rows if r[4] != "?" or any(reg in r[3] for reg in deploy["own_registries"])]
    third = [r for r in rows if r not in ours]
    head = ["namespace", "workload", "kind", "image", "source", "schedule", "hosts", "variant", "argo app"]
    body = "## Our workloads\n\n" + table(head, ours)
    body += "\n\n## Third-party components\n\n" + table(head, third)
    body += "\n\n## Declared but not running (no live Argo app, or scaled down)\n\n" + (table(["namespace", "workload", "image", "source", "file"], sorted(disabled, key=lambda r: (r[0] or "", r[1]))) if disabled else "None.")
    body += "\n\n## Built but not deployed\n\n" + ("\n".join(f"- {o}" for o in sorted(orphans)) or "None.")
    body += "\n\n## Deployed but no tracked source\n\n" + ("\n".join(f"- {u}" for u in sorted(untracked)) or "None.")
    und = deploy.get("undeclared_live") or []
    if und:
        body += "\n\n## Running in the cluster, not declared in the infra repos\n\n" + table(
            ["namespace", "workload", "kind", "images", "argo app", "app source"],
            [[u["namespace"], u["name"], u["kind"], ", ".join(f"`{i}`" for i in u["images"]), u.get("app") or "",
              f"`{u['app_repo']}` `{u['app_path']}`" if u.get("app_repo") else ""] for u in und])
    put_block(target.map_dir / "DEPLOY.md", "deploy", body, DEPLOY_HEADER)


def infra_deploy(project, inv):
    head = ["namespace", "workload", "kind", "image", "schedule", "secret refs", "file"]
    rows = []
    for w in sorted(inv["workloads"], key=lambda w: (w["namespace"] or "", w["name"])):
        imgs = ", ".join(f"`{i['key']}:{i['tag'] or ''}`" for i in w["images"] if not i["init"])
        run = f"cron `{w['schedule']}`" if w["schedule"] else ""
        rows.append([w["namespace"], w["name"], w["kind"], imgs, run, len(w["secret_refs"]), f"`{w['file']}`"])
    ing = [[i["namespace"], ", ".join(i["hosts"]), ", ".join(i["backends"]), f"`{i['file']}`"] for i in inv["ingresses"]]
    apps = [[a["name"], a["dest_namespace"], ", ".join(s.get("path") or s.get("chart") or "" for s in a["sources"]),
             "auto" if a["auto_sync"] else "manual"] for a in inv["apps"]]
    body = f"Inventory at `{inv['sha'][:8]}`: {len(inv['workloads'])} workloads, {len(inv['ingresses'])} ingresses, {len(inv['apps'])} Argo apps.\n\n"
    body += "## Workloads\n\n" + table(head, rows)
    body += "\n\n## Ingresses\n\n" + table(["namespace", "hosts", "backends", "file"], ing)
    if apps:
        body += "\n\n## Argo applications\n\n" + table(["app", "namespace", "source", "sync"], apps)
    if inv["unparsed"]:
        body += "\n\n## Unparsed files\n\n" + "\n".join(f"- `{u}`" for u in inv["unparsed"])
    put_block(project.dir / "DEPLOY.md", "inventory", body, f"# {project.slug}: deploy inventory")


def bridges_map(target, bridges):
    edges = bridges["edges"]
    nodes = {n["id"]: n for n in bridges["nodes"]}
    by_group = defaultdict(list)
    for e in edges:
        by_group[nodes.get(e["from"], {}).get("project") or nodes.get(e["from"], {}).get("namespace") or "other"].append(e)
    body = f"{len(edges)} edges, {len(nodes)} nodes. Confidence: `code` (both sides in code), `config` (deploy env), `fact`, `assumed`.\n"
    for group in sorted(by_group):
        es = by_group[group]
        body += f"\n## {group}\n\n```mermaid\nflowchart LR\n"
        used = sorted({e["from"] for e in es} | {e["to"] for e in es})
        for n in used:
            body += f'  {mermaid_id(n)}["{n}"]\n'
        for e in es:
            body += f'  {mermaid_id(e["from"])} -->|{e["via"]}| {mermaid_id(e["to"])}\n'
        body += "```\n\n" + table(["from", "to", "via", "name", "confidence", "evidence"],
                                  [[e["from"], e["to"], e["via"], e["name"], e["confidence"], "; ".join(f"`{x}`" for x in e["evidence"])] for e in es])
        body += "\n"
    if bridges["unmatched_ports"]:
        body += "\n## Unmatched ports\n\n" + table(["project", "direction", "via", "name", "evidence"],
                                                   [[u["project"], u["direction"], u.get("via"), u.get("name"), u.get("evidence")] for u in bridges["unmatched_ports"]])
    put_block(target.map_dir / "BRIDGES.md", "bridges", body, BRIDGES_HEADER)
